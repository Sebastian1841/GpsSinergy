import test from "node:test"
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { parse, compileScript, compileTemplate } from "@vue/compiler-sfc"

test("orders shows operational KPI and fixed columns without duplicating maintenance under plate", () => {
  const source = readFileSync(new URL("./MaintenanceWorkOrdersTab.vue", import.meta.url), "utf8")
  assert.doesNotMatch(source, /order.type|Estimado:|getCostDeviation|metric.detail/)
  assert.match(source, /<th>Costo real<\/th>/)
  assert.doesNotMatch(source, /showPriority|orders-column-menu|closeColumnsOnBlur/)
  assert.match(source, /<th>Prioridad<\/th>/)
  assert.match(source, /getPriorityClass\(order.priority\)/)
  assert.match(source, /class="expand-table-button"/)
  const metrics = source.slice(source.indexOf("const summaryMetrics"), source.indexOf("const getDeadlineStatus"))
  for (const label of ["OT abiertas", "OT vencidas", "En ejecucion", "En espera"]) assert.ok(metrics.includes(label))
  assert.doesNotMatch(metrics, /Tiempo promedio|Cumplimiento|Costo real/)
})

test("analysis retains performance metrics for finished orders in selected period and compiles", () => {
  const filename = new URL("./MaintenanceCostsTab.vue", import.meta.url)
  const source = readFileSync(filename, "utf8")
  const { descriptor } = parse(source)
  const script = compileScript(descriptor, { id: "analysis-results" })
  const template = compileTemplate({ source: descriptor.template.content, filename: filename.pathname, id: "analysis-results", compilerOptions: { bindingMetadata: script.bindings } })
  assert.deepEqual(template.errors, [])
  assert.match(source, /Resultados de OT finalizadas en el periodo/)
  assert.match(source, /aggregateMaintenanceAnalysisPeriod\(analysisOrderIndex.value, periodStart.value, analysisNow.value\)/)
  assert.match(source, /completedOrderStatistics = computed\(\(\) => periodAnalysis.value.statistics\)/)
  const summary = descriptor.template.content.slice(0, descriptor.template.content.indexOf("analysisSection === 'without-order'"))
  for (const label of ['Costo total registrado', 'OT finalizadas', 'Cumplimiento de plazo', 'Costo mensual', 'Activos con mayor costo']) assert.ok(summary.includes(label))
  assert.doesNotMatch(summary, /Vehiculos monitoreados|Avance del ciclo|Vencimientos por fecha|Cumplimiento por activo|Tiempo promedio|v-model="months"/)
  assert.match(summary, /v-if="hasMonthlyCosts" class="cost-chart"/)
  assert.match(summary, /v-if="activeCostCategoryCount" class="cost-composition"/)
  assert.match(summary, /v-for="row in nonzeroCostComposition"/)
  assert.match(summary, /measurableOrderCount \? completedOrderStatistics.onTimeRate \+ '%' : 'Sin datos'/)
  assert.match(summary, /class="analysis-ranking-empty"/)
  const grid = summary.indexOf('class="analysis-summary-grid"')
  const metrics = summary.indexOf('class="analysis-metrics"')
  const monthly = summary.indexOf('class="card analysis-monthly-card"')
  const composition = summary.indexOf('class="card cost-composition-card"')
  const ranking = summary.indexOf('class="card cost-ranking-card"')
  assert.ok(grid < metrics && metrics < monthly && monthly < composition && composition < ranking)
  assert.match(source, /grid-template-rows: repeat\(3, minmax\(0, 1fr\)\)/)
  assert.match(source, /\.analysis-metrics dd \{ margin: 0; font-size: 26px; line-height: 1\.2;/)
  assert.match(source, /\.analysis-metrics small \{ display: block;/)
  assert.doesNotMatch(summary, /pathLength="100"/)
  assert.match(summary, /row\.percent \* Math\.PI \* 0\.8/)
  assert.match(summary, /compactCost\(tick\)/)
  assert.match(summary, /class="cost-bar-value"/)
  assert.match(summary, /tabindex="0" :aria-label="bar.label/)
  assert.match(source, /@container \(max-width: 400px\)/)
  assert.match(summary, /'is-current-month': index === monthlyCosts.length - 1/)
  assert.match(source, /\.analysis-summary-grid \.cost-plot \.is-current-month i \{ background: #102372;/)
  assert.match(source, /width: min\(190px, 100%\)/)
})

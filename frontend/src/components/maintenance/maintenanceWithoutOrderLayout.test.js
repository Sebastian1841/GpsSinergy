import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { parse, compileScript, compileTemplate } from '@vue/compiler-sfc'

test('plans without OT shows only real actionable plans without samples or export controls', () => {
  const source = readFileSync(new URL('./MaintenanceCostsTab.vue', import.meta.url), 'utf8')
  assert.doesNotMatch(source, /class="kpis no-order-kpis"|class="no-order-insights"/)
  assert.doesNotMatch(source, /pending-plan-summary|pending-type-breakdown|sampleTypeChartRows|previewTypeChart/)
  assert.doesNotMatch(source, /Datos de muestra|pendingSamples|showPendingSamples|isSample|pending-table-export/)
  assert.match(source, /v-if="\['due', 'overdue'\].includes\(item.status\)"/)
  assert.match(source, /class="card table-card pending-table-only"/)
  assert.match(source, /class="filters pending-table-filters"/)
  assert.match(source, /class="pending-table-statuses" aria-label="Estado del plan"/)
  assert.match(source, /pending-table-statuses \{[^}]*margin: 0;/)
  assert.match(source, /Activo \/ Mantencion/)
  assert.match(source, /class="pending-plan-name"/)
  assert.match(source, /sortFleetPlansByPriority\(withoutOrder.value/)
  assert.match(source, /visiblePlans.value.filter\(\(item\) => \['due', 'overdue'\].includes\(item.status\) && !hasOrder\(item\)\)/)
  const statusOptions = source.slice(source.indexOf('const noOrderOptions ='), source.indexOf('const norm ='))
  assert.match(statusOptions, /Todas/)
  assert.match(statusOptions, /Vencidas/)
  assert.match(statusOptions, /Proximas/)
  assert.doesNotMatch(statusOptions, /current|Al dia/)
  assert.match(source, /item.actualLabel/)
  assert.match(source, /pendingPlanDueLabel\(item\)/)
  assert.match(source, /criterion\(item\) === 'Tiempo' \? '-'/)
  assert.doesNotMatch(source, /noOrderPeriod|Próximos 90/)
  assert.match(source, /v-if="noOrderPageCount > 1"/)
  assert.match(source, /v-if="filteredNoOrder.length > 10"/)
  assert.match(source, /pageSize = ref\(10\)/)
  assert.match(source, /getWorkOrderPage\(filteredNoOrder.value, noOrderPage.value, pageSize.value\)/)
  assert.match(source, /v-for="page in noOrderPageButtons"/)
  assert.match(source, />Planes sin OT <span class="pending-title-count">/)
  assert.doesNotMatch(source, /\.pending-table-heading h2 > span/)
  assert.match(source, /noOrderPagination.value.rows/)
  assert.match(source, /noOrderPage >= noOrderPageCount/)
  assert.match(source, /class="no-order-empty"/)
  const { descriptor } = parse(source)
  const script = compileScript(descriptor, { id: 'without-order' })
  const result = compileTemplate({ source: descriptor.template.content, filename: 'MaintenanceCostsTab.vue', id: 'without-order', compilerOptions: { bindingMetadata: script.bindings } })
  assert.deepEqual(result.errors, [])
})
